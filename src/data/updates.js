export const getUpdateBySlug = (slug) => updates.find((u) => u.slug === slug)

export const getAdjacentUpdates = (slug) => {
  const index = updates.findIndex((u) => u.slug === slug)
  const prev = index > 0 ? updates[index - 1] : null
  const next = index >= 0 && index < updates.length - 1 ? updates[index + 1] : null
  return { prev, next }
}
